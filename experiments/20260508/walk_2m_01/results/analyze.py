"""
CORGI Experiment Analysis — 20260508 walk_2m_01 (replay_fixed bag)
Steps 2 (Inner EKF bias) + 3 (Outer Fusion) + 4 (LiDAR Quality)
No VICON available for this session — all comparisons are EKF vs odom_mapping.
Generated by corgi-data-analysis skill.
"""

import sqlite3
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from scipy.interpolate import interp1d
from scipy.spatial.transform import Rotation
from rclpy.serialization import deserialize_message
from nav_msgs.msg import Odometry
from geometry_msgs.msg import Vector3, Vector3Stamped
import os

# ── Paths ─────────────────────────────────────────────────────────────────────
BASE    = os.path.dirname(os.path.abspath(__file__))
RESULTS = BASE

BAG_DB = os.path.join(BASE, '..', 'bags',
         'replay_fixed_20260510_034717',
         'replay_fixed_20260510_034717_0.db3')

# T_{odom←camera_init}: obtained from fusion node log during recording
# If not available from log, set to identity and note in report.
# Format: [tx, ty, tz] metres and [qw, qx, qy, qz]
T_CO_t = np.array([0.092, -0.021, 0.178])    # from ~/.ros/log/corgi_fusion_node_327512_1778355612276.log
T_CO_q = np.array([0.6988, 0.1261, 0.1264, 0.6927])  # [qw, qx, qy, qz]

# ── Helpers ───────────────────────────────────────────────────────────────────
def interp_to(src_t, src_val, tgt_t):
    f = interp1d(src_t, src_val, bounds_error=False, fill_value=np.nan)
    return f(tgt_t)

def quat_to_rpy(qw, qx, qy, qz):
    R = Rotation.from_quat(np.column_stack([qx, qy, qz, qw]))
    return R.as_euler('ZYX')[:, ::-1]   # [roll, pitch, yaw] in radians

def quat_to_rotmat(qw, qx, qy, qz):
    return Rotation.from_quat([qx, qy, qz, qw]).as_matrix()

# ── Load all topics from bag ──────────────────────────────────────────────────
print(f'Loading bag: {BAG_DB}')
conn = sqlite3.connect(BAG_DB)
cur  = conn.cursor()
cur.execute("SELECT name, id FROM topics")
topics = {r[0]: r[1] for r in cur.fetchall()}
print('Topics:', list(topics.keys()))

def fetch_msgs(topic):
    cur.execute(f"SELECT timestamp, data FROM messages "
                f"WHERE topic_id={topics[topic]} ORDER BY timestamp")
    return cur.fetchall()

rows_ekf  = fetch_msgs('/ekf')
rows_ba   = fetch_msgs('/ekf/ba')
rows_bw   = fetch_msgs('/ekf/bw')
rows_map  = fetch_msgs('/odom_mapping')
rows_bv   = fetch_msgs('/fusion/bv')
rows_lid  = fetch_msgs('/lidar_odom')
conn.close()

# t0 = first EKF message timestamp
t0_ns = rows_ekf[0][0]

def t_rel(ts_ns):
    return (ts_ns - t0_ns) / 1e9

# ── Inner EKF ─────────────────────────────────────────────────────────────────
print('Parsing /ekf ...')
ekf = {k: [] for k in ['t','px','py','pz','vx','vy','vz',
                        'qw','qx','qy','qz',
                        'cov_px','cov_py','cov_pz',
                        'cov_vx','cov_vy','cov_vz']}
for ts, data in rows_ekf:
    msg = deserialize_message(data, Odometry)
    ekf['t'].append(t_rel(ts))
    ekf['px'].append(msg.pose.pose.position.x)
    ekf['py'].append(msg.pose.pose.position.y)
    ekf['pz'].append(msg.pose.pose.position.z)
    ekf['vx'].append(msg.twist.twist.linear.x)
    ekf['vy'].append(msg.twist.twist.linear.y)
    ekf['vz'].append(msg.twist.twist.linear.z)
    ekf['qw'].append(msg.pose.pose.orientation.w)
    ekf['qx'].append(msg.pose.pose.orientation.x)
    ekf['qy'].append(msg.pose.pose.orientation.y)
    ekf['qz'].append(msg.pose.pose.orientation.z)
    c  = msg.pose.covariance
    c2 = msg.twist.covariance
    ekf['cov_px'].append(c[0]); ekf['cov_py'].append(c[7]); ekf['cov_pz'].append(c[14])
    ekf['cov_vx'].append(c2[0]); ekf['cov_vy'].append(c2[7]); ekf['cov_vz'].append(c2[14])
for k in ekf:
    ekf[k] = np.array(ekf[k])
rpy_ekf = quat_to_rpy(ekf['qw'], ekf['qx'], ekf['qy'], ekf['qz'])
print(f'EKF: {len(ekf["t"])} msgs, {ekf["t"][-1]:.1f} s')

# ── Accel bias ────────────────────────────────────────────────────────────────
ba = {'t':[], 'x':[], 'y':[], 'z':[]}
for ts, data in rows_ba:
    msg = deserialize_message(data, Vector3)
    ba['t'].append(t_rel(ts)); ba['x'].append(msg.x)
    ba['y'].append(msg.y); ba['z'].append(msg.z)
for k in ba:
    ba[k] = np.array(ba[k])

# ── Gyro bias ─────────────────────────────────────────────────────────────────
bw = {'t':[], 'x':[], 'y':[], 'z':[]}
for ts, data in rows_bw:
    msg = deserialize_message(data, Vector3)
    bw['t'].append(t_rel(ts)); bw['x'].append(msg.x)
    bw['y'].append(msg.y); bw['z'].append(msg.z)
for k in bw:
    bw[k] = np.array(bw[k])

# ── odom_mapping ──────────────────────────────────────────────────────────────
print('Parsing /odom_mapping ...')
odom = {k: [] for k in ['t','px','py','pz','vx','vy','vz','qw','qx','qy','qz']}
for ts, data in rows_map:
    msg = deserialize_message(data, Odometry)
    odom['t'].append(t_rel(ts))
    odom['px'].append(msg.pose.pose.position.x)
    odom['py'].append(msg.pose.pose.position.y)
    odom['pz'].append(msg.pose.pose.position.z)
    odom['vx'].append(msg.twist.twist.linear.x)
    odom['vy'].append(msg.twist.twist.linear.y)
    odom['vz'].append(msg.twist.twist.linear.z)
    odom['qw'].append(msg.pose.pose.orientation.w)
    odom['qx'].append(msg.pose.pose.orientation.x)
    odom['qy'].append(msg.pose.pose.orientation.y)
    odom['qz'].append(msg.pose.pose.orientation.z)
for k in odom:
    odom[k] = np.array(odom[k])
rpy_odom = quat_to_rpy(odom['qw'], odom['qx'], odom['qy'], odom['qz'])
print(f'odom_mapping: {len(odom["t"])} msgs')

# ── fusion/bv ─────────────────────────────────────────────────────────────────
print('Parsing /fusion/bv ...')
bv = {'t':[], 'x':[], 'y':[], 'z':[]}
for ts, data in rows_bv:
    msg = deserialize_message(data, Vector3Stamped)
    bv['t'].append(t_rel(ts))
    bv['x'].append(msg.vector.x)
    bv['y'].append(msg.vector.y)
    bv['z'].append(msg.vector.z)
for k in bv:
    bv[k] = np.array(bv[k])
print(f'fusion/bv: {len(bv["t"])} msgs')

# ── lidar_odom ────────────────────────────────────────────────────────────────
print('Parsing /lidar_odom ...')
lidar_raw = {k: [] for k in ['t','px','py','pz','qw','qx','qy','qz']}
for ts, data in rows_lid:
    msg = deserialize_message(data, Odometry)
    lidar_raw['t'].append(t_rel(ts))
    lidar_raw['px'].append(msg.pose.pose.position.x)
    lidar_raw['py'].append(msg.pose.pose.position.y)
    lidar_raw['pz'].append(msg.pose.pose.position.z)
    lidar_raw['qw'].append(msg.pose.pose.orientation.w)
    lidar_raw['qx'].append(msg.pose.pose.orientation.x)
    lidar_raw['qy'].append(msg.pose.pose.orientation.y)
    lidar_raw['qz'].append(msg.pose.pose.orientation.z)
for k in lidar_raw:
    lidar_raw[k] = np.array(lidar_raw[k])

# Apply T_{odom←camera_init}
R_co = quat_to_rotmat(*T_CO_q)
p_raw = np.column_stack([lidar_raw['px'], lidar_raw['py'], lidar_raw['pz']])
p_odom = (R_co @ p_raw.T).T + T_CO_t
lidar = dict(lidar_raw)
lidar['px_odom'] = p_odom[:, 0]
lidar['py_odom'] = p_odom[:, 1]
lidar['pz_odom'] = p_odom[:, 2]
print(f'lidar_odom: {len(lidar["t"])} msgs')

# ── Bag duration and walk phase ───────────────────────────────────────────────
t_total = ekf['t'][-1]
# 15s 後機器人被抬起，資料有干擾，只分析前 15s
t_walk_end = 15.0
print(f'Bag duration: {t_total:.1f} s, 分析區間: 0 – {t_walk_end:.1f} s (15s 後機器人被抬起)')

# ── 套用分析時間窗口遮罩 ──────────────────────────────────────────────────────
def mask_by_time(d, t_end):
    m = d['t'] <= t_end
    return {k: v[m] for k, v in d.items()}

ekf_w   = mask_by_time(ekf, t_walk_end)
odom_w  = mask_by_time(odom, t_walk_end)
bv_w    = mask_by_time(bv, t_walk_end)
lidar_w = mask_by_time(lidar, t_walk_end)
ba_w    = mask_by_time(ba, t_walk_end)
bw_w    = mask_by_time(bw, t_walk_end)
rpy_ekf_w  = rpy_ekf[ekf['t'] <= t_walk_end]
rpy_odom_w = rpy_odom[odom['t'] <= t_walk_end]

# ══════════════════════════════════════════════════════════════════════════════
# Metrics
# ══════════════════════════════════════════════════════════════════════════════

# ── 3.1 odom_mapping vs EKF position ─────────────────────────────────────────
ekf_px_on_map = interp_to(ekf_w['t'], ekf_w['px'], odom_w['t'])
ekf_py_on_map = interp_to(ekf_w['t'], ekf_w['py'], odom_w['t'])
ekf_pz_on_map = interp_to(ekf_w['t'], ekf_w['pz'], odom_w['t'])

err_map_vs_ekf_2d = np.sqrt(
    (odom_w['px'] - ekf_px_on_map)**2 +
    (odom_w['py'] - ekf_py_on_map)**2)
valid_map = ~np.isnan(err_map_vs_ekf_2d)
metrics_map_pos = {
    'RMSE_2D_vs_EKF': float(np.sqrt(np.mean(err_map_vs_ekf_2d[valid_map]**2))),
    'MAX_2D_vs_EKF':  float(np.max(err_map_vs_ekf_2d[valid_map])),
    'final_odom':     (float(odom_w['px'][-1]), float(odom_w['py'][-1])),
    'final_ekf':      (float(ekf_w['px'][-1]),  float(ekf_w['py'][-1])),
}
print(f"odom_mapping vs EKF 2D RMSE: {metrics_map_pos['RMSE_2D_vs_EKF']:.4f} m")

# ── 3.2 odom_mapping yaw vs EKF ───────────────────────────────────────────────
ekf_yaw_on_map = interp_to(ekf_w['t'], np.degrees(rpy_ekf_w[:, 2]), odom_w['t'])
valid_yaw = ~np.isnan(ekf_yaw_on_map)
metrics_map_yaw = {
    'RMSE_yaw_vs_EKF_deg': float(np.sqrt(np.mean(
        (rpy_odom_w[valid_yaw, 2] - ekf_yaw_on_map[valid_yaw])**2))),
    'final_yaw_odom': float(np.degrees(rpy_odom_w[-1, 2])),
    'final_yaw_ekf':  float(np.degrees(rpy_ekf_w[-1, 2])),
}
print(f"odom yaw RMSE vs EKF: {metrics_map_yaw['RMSE_yaw_vs_EKF_deg']:.3f}°")

# ── 3.3 fusion/bv vs EKF velocity ────────────────────────────────────────────
ekf_vx_on_bv = interp_to(ekf_w['t'], ekf_w['vx'], bv_w['t'])
ekf_vy_on_bv = interp_to(ekf_w['t'], ekf_w['vy'], bv_w['t'])
valid_bv = ~np.isnan(ekf_vx_on_bv)
metrics_bv = {
    'RMSE_vx_vs_EKF': float(np.sqrt(np.nanmean((bv_w['x'][valid_bv] - ekf_vx_on_bv[valid_bv])**2))),
    'RMSE_vy_vs_EKF': float(np.sqrt(np.nanmean((bv_w['y'][valid_bv] - ekf_vy_on_bv[valid_bv])**2))),
}
print(f"fusion/bv RMSE vs EKF: vx={metrics_bv['RMSE_vx_vs_EKF']:.4f}, vy={metrics_bv['RMSE_vy_vs_EKF']:.4f} m/s")

# ── 4. LiDAR quality ──────────────────────────────────────────────────────────
dt_lidar = np.diff(lidar_w['t'])
dp_lidar = np.sqrt(np.diff(lidar_w['px_odom'])**2 + np.diff(lidar_w['py_odom'])**2)
metrics_lidar = {
    'count':       len(lidar_w['t']),
    'mean_dt_ms':  float(dt_lidar.mean() * 1000),
    'gaps_500ms':  int(np.sum(dt_lidar > 0.5)),
    'jumps_5cm':   int(np.sum(dp_lidar > 0.05)),
}
print(f"LiDAR: count={metrics_lidar['count']}, "
      f"mean_dt={metrics_lidar['mean_dt_ms']:.1f} ms, "
      f"gaps={metrics_lidar['gaps_500ms']}, "
      f"jumps={metrics_lidar['jumps_5cm']}")

# ── Bias statistics ────────────────────────────────────────────────────────────
bias_stats = {}
for bias_data, bname in [(ba_w, 'ba'), (bw_w, 'bw')]:
    for ax in ['x', 'y', 'z']:
        vals = bias_data[ax]
        bias_stats[f'{bname}_{ax}_init']   = float(vals[0]) if len(vals) else np.nan
        bias_stats[f'{bname}_{ax}_steady']  = float(np.mean(vals[-50:])) if len(vals) >= 50 else np.nan
        bias_stats[f'{bname}_{ax}_std']     = float(np.std(vals[-50:])) if len(vals) >= 50 else np.nan

